def apply_topic_renames():
    renamed_count = 0
    all_files = sorted(glob.glob('data/argon_packets/packet_*.json') + glob.glob('data/agy_packets/packet_*.json'))
    for path in all_files:
        norm_path = path.replace('\\', '/')
        with open(path, 'r', encoding='utf-8') as f:
            pkg = json.load(f)
        modified = False
        for r in pkg.get('rounds', []):
            r_idx = r.get('index')
            for t in r.get('topics', []):
                t_name = t.get('name', '').strip()
                key = (norm_path, r_idx, t_name)
                if key in TOPIC_RENAMES:
                    new_name = TOPIC_RENAMES[key]
                    if len(new_name) <= 40:
                        t['name'] = new_name
                        modified = True
                        renamed_count += 1
                    else:
                        print(f"WARNING: new name exceeds 40 chars: {new_name}")
        if modified:
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(pkg, f, ensure_ascii=False, indent=2)
                f.write('\n')
    print(f"Applied {renamed_count} topic renames across packages.")


def apply_clue_replacements():
    clue_replaced_count = 0
    for repl in CLUE_REPLACEMENTS:
        path = repl['file']
        if not os.path.exists(path):
            print(f"File not found: {path}")
            continue
        with open(path, 'r', encoding='utf-8') as f:
            pkg = json.load(f)
        modified = False
        target_r = repl['round']
        target_old_ans = repl['old_ans_part'].lower()
        for r in pkg.get('rounds', []):
            if r.get('index') == target_r:
                for t in r.get('topics', []):
                    for c in t.get('clues', []):
                        if target_old_ans in c.get('answer', '').lower():
                            c['question'] = repl['question']
                            c['answer'] = repl['answer']
                            modified = True
                            clue_replaced_count += 1
                            break
                    if modified:
                        break
            if modified:
                break
        if modified:
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(pkg, f, ensure_ascii=False, indent=2)
                f.write('\n')
        else:
            print(f"Note: replacement target not matched in {path} R{target_r} for ans '{repl['old_ans_part']}'")
    print(f"Applied {clue_replaced_count} clue replacements.")


if __name__ == '__main__':
    apply_topic_renames()
    apply_clue_replacements()
